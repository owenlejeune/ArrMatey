package com.dnfapps.arrmatey.monitoring.model

import com.dnfapps.arrmatey.instances.model.InstanceType
import com.dnfapps.arrmatey.tracearr.api.model.TracearrServerType

data class PlaybackHistoryItem(
    val id: String,
    val instanceId: Long,
    val instanceType: InstanceType,
    val instanceLabel: String,
    val dateEpochSeconds: Long,
    val username: String,
    val userDisplayName: String,
    val userAvatarUrl: String? = null,
    val title: String,
    val displayTitle: String,
    val mediaType: PlaybackMediaType = PlaybackMediaType.Other,
    val tmdbId: Long? = null,
    val ratingKey: String? = null,
    val player: String? = null,
    val platform: String? = null,
    val ipAddress: String? = null,
    val durationSeconds: Long? = null,
    val percentComplete: Int? = null,
    val streamDecision: PlaybackStreamDecision = PlaybackStreamDecision.DirectPlay,
    val posterUrl: String? = null,
    val serverName: String? = null,
    val serverType: TracearrServerType? = null,
    val subtitle: String? = null,
    val resolution: String? = null,
    val watched: Boolean? = null,
)

fun PlaybackHistoryItem.toStreamSession(): PlaybackStreamSession = PlaybackStreamSession(
    sessionId = id,
    sessionKey = ratingKey ?: id,
    instanceId = instanceId,
    instanceLabel = instanceLabel,
    instanceType = instanceType,
    serverName = serverName ?: instanceLabel,
    serverType = serverType,
    ratingKey = ratingKey,
    tmdbId = tmdbId,
    mediaType = mediaType,
    title = title,
    parentTitle = subtitle,
    grandparentTitle = null,
    displayTitle = displayTitle,
    subtitle = subtitle,
    year = null,
    username = username,
    userDisplayName = userDisplayName,
    userAvatarUrl = userAvatarUrl,
    player = player,
    device = player,
    platform = platform,
    ipAddress = ipAddress,
    location = null,
    progressPercent = ((percentComplete ?: 0) / 100f).coerceIn(0f, 1f),
    progressMs = durationSeconds?.let { sec -> (percentComplete ?: 0) * sec * 10L },
    totalDurationMs = durationSeconds?.let { it * 1000L },
    state = if ((percentComplete ?: 0) >= 90 || watched == true) "watched" else "stopped",
    streamDecision = streamDecision,
    isTranscoding = streamDecision == PlaybackStreamDecision.Transcode,
    videoResolution = resolution,
    posterUrl = posterUrl,
    canTerminate = false,
)
